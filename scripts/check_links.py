"""Offline check of relative links in the repository's Markdown files.

    python scripts/check_links.py          # every tracked *.md file
    python scripts/check_links.py README.md lessons/04-chunking/README.fa.md

For every ``[text](target)`` and ``![alt](target)`` outside fenced code blocks
and inline code, a relative target must exist on disk (file or folder). For a
``#fragment`` pointing at a Markdown file (or the same file), the heading must
exist, using GitHub's slug rules (which keep Persian letters). External links
(``http``, ``mailto``, ...) are not fetched: the check never touches the network.

The docs site generates ``docs/lessons/<slug>.md`` from ``lessons/<slug>/README.fa.md``
(``scripts/mkdocs_hooks.py``), so links from ``docs/`` to those pages are resolved
to the lesson README.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import unicodedata
from functools import cache
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
LINK = re.compile(r"!?\[(?:[^\[\]]|\[[^\]]*\])*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
INLINE_CODE = re.compile(r"(`+)(?:(?!\1).)+\1")
FENCE = re.compile(r"^\s*(```|~~~)")
HEADING = re.compile(r"^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
SKIP_DIRS = {".git", "site", "dist", "build", ".venv", "venv", "node_modules"}


def markdown_files() -> list[Path]:
    try:
        out = subprocess.run(
            ["git", "ls-files", "*.md"], cwd=ROOT, capture_output=True, text=True, check=True
        ).stdout
        return [ROOT / line for line in out.splitlines() if line]
    except (OSError, subprocess.CalledProcessError):
        return [p for p in ROOT.rglob("*.md") if not SKIP_DIRS & set(p.relative_to(ROOT).parts)]


def prose_lines(text: str) -> list[tuple[int, str]]:
    """Lines outside fenced code blocks, with inline code removed."""
    lines, in_fence = [], False
    for number, line in enumerate(text.splitlines(), 1):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if not in_fence:
            lines.append((number, INLINE_CODE.sub("", line)))
    return lines


def github_slug(heading: str) -> str:
    """GitHub's anchor for a heading: lower-case, punctuation dropped, spaces → '-'."""
    text = re.sub(r"<[^>]+>", "", heading)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)  # links keep their text
    text = text.replace("`", "").lower()
    kept = []
    for ch in text:
        cat = unicodedata.category(ch)
        if ch in " -_" or cat[0] in "LN" or cat in ("Mn", "Mc") or ch == "‌":
            kept.append(ch)
    return "".join(kept).replace(" ", "-")


@cache
def anchors(path: Path) -> frozenset[str]:
    seen: dict[str, int] = {}
    result = set()
    for _, line in prose_lines(path.read_text(encoding="utf-8")):
        m = HEADING.match(line)
        if not m:
            continue
        slug = github_slug(m.group(2))
        n = seen.get(slug, 0)
        seen[slug] = n + 1
        result.add(slug if n == 0 else f"{slug}-{n}")
    for anchor in re.findall(r"<a\s+(?:name|id)=\"([^\"]+)\"", path.read_text(encoding="utf-8")):
        result.add(anchor)
    return frozenset(result)


def site_lesson(dest: Path) -> Path | None:
    """``docs/lessons/<slug>.md`` (generated by the docs site) → the lesson README."""
    if dest.parent == ROOT / "docs" / "lessons" and dest.suffix == ".md":
        readme = ROOT / "lessons" / dest.stem / "README.fa.md"
        return readme if readme.is_file() else None
    return None


def check_file(path: Path) -> list[str]:
    errors = []
    rel = path.relative_to(ROOT)
    for number, line in prose_lines(path.read_text(encoding="utf-8")):
        for target in LINK.findall(line):
            if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("//"):
                continue  # external: not checked offline
            file_part, _, fragment = target.partition("#")
            dest = (path.parent / file_part).resolve() if file_part else path
            dest = site_lesson(dest) or dest
            if file_part and not dest.exists():
                errors.append(f"{rel}:{number}: broken link → {target}")
                continue
            try:
                dest.relative_to(ROOT)
            except ValueError:
                errors.append(f"{rel}:{number}: link leaves the repository → {target}")
                continue
            if (
                fragment
                and dest.suffix == ".md"
                and dest.is_file()
                and unquote(fragment).lower() not in anchors(dest)
            ):
                errors.append(f"{rel}:{number}: missing heading #{fragment} in {target}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("files", nargs="*", type=Path)
    args = parser.parse_args()
    files = [p.resolve() for p in args.files] or markdown_files()
    errors = [e for f in files for e in check_file(f)]
    for e in errors:
        print(f"✘ {e}", file=sys.stderr)
    if errors:
        print(f"\n{len(errors)} broken link(s) in {len(files)} Markdown files", file=sys.stderr)
        return 1
    print(f"✔ all relative links resolve ({len(files)} Markdown files checked, offline)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
